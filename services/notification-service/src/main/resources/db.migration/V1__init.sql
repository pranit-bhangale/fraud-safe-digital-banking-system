
CREATE TABLE IF NOT EXISTS notification_audits
(
    id                UUID         NOT NULL,
    event_id          VARCHAR(64)  NOT NULL,
    source            VARCHAR(255) NOT NULL,
    destination       VARCHAR(255) NOT NULL,
    status            VARCHAR(32)  NOT NULL,
    notification_type VARCHAR(32)  NOT NULL,
    channel           VARCHAR(32)  NOT NULL,
    error_message     VARCHAR(2000),
    attempts          INTEGER      NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ,
    version           BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT pk_notification_audits
    PRIMARY KEY (id),

    CONSTRAINT ck_notification_audits_event_id_not_blank
    CHECK (length(btrim(event_id)) > 0),

    CONSTRAINT ck_notification_audits_source_not_blank
    CHECK (length(btrim(source)) > 0),

    CONSTRAINT ck_notification_audits_destination_not_blank
    CHECK (length(btrim(destination)) > 0),

    CONSTRAINT ck_notification_audits_status
    CHECK (
              status IN (
              'QUEUED',
              'PROCESSING',
              'SENT',
              'DELIVERED',
              'FAILED'
                        )
    ),

    CONSTRAINT ck_notification_audits_type
    CHECK (
              notification_type IN (
              'FRAUD_ALERT',
              'OTP',
              'WELCOME',
              'TXN_SUCCESS',
              'TXN_FAILED'
                                   )
    ),

    CONSTRAINT ck_notification_audits_channel
    CHECK (
              channel IN (
              'SMS',
              'EMAIL',
              'INTERNAL',
              'PUSH'
                         )
    ),

    CONSTRAINT ck_notification_audits_attempts
    CHECK (attempts >= 0),

    CONSTRAINT ck_notification_audits_version
    CHECK (version >= 0)
    );

-- Event lookup
CREATE INDEX idx_notification_audits_event_id
    ON notification_audits(event_id);

-- Status lookup
CREATE INDEX idx_notification_audits_status
    ON notification_audits(status);

-- Notification type lookup
CREATE INDEX idx_notification_audits_type
    ON notification_audits(notification_type);

-- Channel lookup
CREATE INDEX idx_notification_audits_channel
    ON notification_audits(channel);

-- Audit history
CREATE INDEX idx_notification_audits_created_at
    ON notification_audits(created_at DESC);

-- Failed notification lookup
CREATE INDEX idx_notification_audits_failures
    ON notification_audits(created_at DESC)
    WHERE status = 'FAILED';

COMMENT ON TABLE notification_audits
    IS 'Audit trail of notification processing and delivery lifecycle';

COMMENT ON COLUMN notification_audits.id
    IS 'Primary key UUID generated by Hibernate';

COMMENT ON COLUMN notification_audits.event_id
    IS 'Business event identifier from Kafka or RabbitMQ';

COMMENT ON COLUMN notification_audits.source
    IS 'Source microservice that generated the notification';

COMMENT ON COLUMN notification_audits.destination
    IS 'Notification recipient address or destination';

COMMENT ON COLUMN notification_audits.status
    IS 'Current notification processing status';

COMMENT ON COLUMN notification_audits.notification_type
    IS 'Notification business type';

COMMENT ON COLUMN notification_audits.channel
    IS 'Notification delivery channel';

COMMENT ON COLUMN notification_audits.error_message
    IS 'Failure details when notification processing fails';

COMMENT ON COLUMN notification_audits.attempts
    IS 'Number of notification delivery attempts';

COMMENT ON COLUMN notification_audits.created_at
    IS 'Audit record creation timestamp';

COMMENT ON COLUMN notification_audits.updated_at
    IS 'Last audit record update timestamp';

COMMENT ON COLUMN notification_audits.version
    IS 'Optimistic locking version';